export const GENERATED_START = '<!-- shard:generated -->'
export const GENERATED_END = '<!-- /shard:generated -->'

export interface ErrorCode {
  code: string
  hint?: string
  /** Package or file it comes from. */
  source: string
}

function fieldRow(name: string, schema: JsonSchema): string {
  const type = describeType(schema)
  const def = schema.default === undefined ? '' : `\`${JSON.stringify(schema.default)}\``
  const range = [
    schema.minimum !== undefined ? `≥ ${schema.minimum}` : '',
    schema.maximum !== undefined ? `≤ ${schema.maximum}` : '',
    schema['x-unit'] ? `${schema['x-unit']}` : '',
  ]
    .filter(Boolean)
    .join(', ')
  const presets = schema['x-presets']
    ? ` Presets: ${Object.keys(schema['x-presets'] as object).join(', ')}.`
    : ''
  const description = `${(schema.description as string | undefined) ?? ''}${presets}`.replace(
    /\|/g,
    '\\|',
  )
  return `| \`${name}\` | ${type} | ${def} | ${range} | ${description} |`
}

function describeType(schema: JsonSchema): string {
  if (schema.anyOf) return (schema.anyOf as JsonSchema[]).map(describeType).join(' or ')
  if (schema.enum) return (schema.enum as string[]).map((v) => `\`"${v}"\``).join(' \\| ')
  if (schema.type === 'array') {
    const n =
      schema.minItems === schema.maxItems && schema.minItems !== undefined
        ? `${schema.minItems}`
        : ''
    return `${describeType((schema.items as JsonSchema) ?? {})}[${n}]`
  }
  if (schema.type === 'object' && schema.properties && (schema.properties as JsonSchema).guid)
    return 'asset ref'
  return (schema.type as string | undefined) ?? 'any'
}

/** A readable catalog of components: the same facts as the JSON Schemas, for agents to skim. */
export function renderComponentCatalog(defs: readonly ComponentDef[] = allComponents()): string {
  const visible = defs.filter((d) => !d.name.startsWith('test/'))
  const lines = [
    '# Components',
    '',
    'Generated by `shard docs` from the registry. Use these names as keys under `components` in scene files.',
    '',
  ]
  for (const def of visible) {
    lines.push(`## \`${def.name}\``, '')
    if (def.description) lines.push(def.description, '')
    if (!def.serializable) lines.push('_Computed by the engine; never written in scene files._', '')
    if (def.requires.length > 0)
      lines.push(`Brings along: ${def.requires.map((r) => `\`${r.name}\``).join(', ')}.`, '')
    const props = (def.jsonSchema().properties ?? {}) as Record<string, JsonSchema>
    if (Object.keys(props).length === 0) {
      lines.push('Tag (no fields).', '')
      continue
    }
    lines.push('| Field | Type | Default | Range | Description |', '|---|---|---|---|---|')
    for (const [name, schema] of Object.entries(props)) lines.push(fieldRow(name, schema))
    if (def.name === 'core/Transform') {
      lines.push(
        '| `rotationEuler` | number[3] | | degrees | Scene files only: rotation as X, then Y, then Z degrees. |',
      )
    }
    lines.push('')
  }
  return lines.join('\n')
}

export function renderErrorCatalog(codes: readonly ErrorCode[]): string {
  const lines = [
    '# Error codes',
    '',
    'Every engine error is a `ShardError` with one of these codes.',
    '',
  ]
  lines.push('| Code | Source | Hint |', '|---|---|---|')
  for (const c of [...codes].sort((a, b) => a.code.localeCompare(b.code))) {
    lines.push(`| \`${c.code}\` | ${c.source} | ${(c.hint ?? '').replace(/\|/g, '\\|')} |`)
  }
  return `${lines.join('\n')}\n`
}

/** Importers: which files they handle, what they produce, and their `.meta` settings. */
export function renderAssetCatalog(importers: readonly ImporterDef[] = allImporters()): string {
  const visible = importers.filter((i) => !i.name.startsWith('test'))
  const lines = [
    '# Assets',
    '',
    'Generated by `shard docs`. Files under the asset roots (`assetRoots` in shard.json) are imported',
    'by extension. Each gets a `.meta` next to it with its guid and import settings; commit both.',
    'Reference assets in scenes by path: `{ "path": "materials/hull.material.json" }`, or a',
    'sub-asset with `#`: `{ "path": "assets/ship.glb#Mesh/Hull" }`.',
    '',
  ]
  for (const importer of visible) {
    lines.push(`## \`${importer.name}\``, '')
    lines.push(`Files: ${importer.extensions.map((e) => `\`*${e}\``).join(', ')}`, '')
    const props = (importer.settings.jsonSchema().properties ?? {}) as Record<string, JsonSchema>
    if (Object.keys(props).length === 0) {
      lines.push('No import settings.', '')
      continue
    }
    lines.push('| Setting | Type | Default | Range | Description |', '|---|---|---|---|---|')
    for (const [name, schema] of Object.entries(props)) lines.push(fieldRow(name, schema))
    lines.push('')
  }
  return `${lines.join('\n')}\n`
}

