function agentsBlock(manifest: ManifestValue): string {
  return `${GENERATED_START}
# ${manifest.name}

A [Shard](https://github.com/) project. The engine is data-first: scenes are JSON validated against
component schemas, game code is ECS (components, systems) in \`scripts/\`.

## Commands

\`\`\`sh
shard validate --json     # manifest, assets, scenes: every error with a path
shard import --json       # import new and changed asset files
shard mv <from> <to>      # move an asset and rewrite references to it
shard run --frames 600    # headless run
shard screenshot ${manifest.startScene} --out shot.png
shard test --json         # gameplay tests in tests/
shard check --json        # type-check scripts: file, line, column
shard dev                 # play it in a browser; saves hot reload in place
shard docs                # regenerate this block, .agents/, and .shard/schemas/
shard mcp                 # MCP server for this project (see .mcp.json)
\`\`\`

## Where things are

- \`shard.json\`: manifest (start scene: \`${manifest.startScene}\`, seed ${manifest.seed}, plugins: ${manifest.plugins.join(', ')})
- \`scripts/main.ts\`: the project plugin; project types are named \`${manifest.name}/<Name>\`
- \`scenes/\`: scene files; \`tests/\`: gameplay tests; \`shaders/\`: \`project::\` shader modules
- \`${manifest.assetRoots.join('/`, `')}/\`: asset files, each with a \`.meta\` (guid, import settings)
- \`.agents/components.md\`: every component and field; \`.agents/assets.md\`: importers;
  \`.agents/errors.md\`: error codes
- \`.agents/skills/\`: recipes for common tasks

Engine plugins available: ${Object.entries(BUILTIN_PLUGINS)
    .map(([n, d]) => `\`${n}\` (${d})`)
    .join('; ')}.
${GENERATED_END}`
}

/** Replaces the generated block in AGENTS.md, keeping everything outside the markers. */
export function mergeAgentsMd(existing: string | undefined, manifest: ManifestValue): string {
  const block = agentsBlock(manifest)
  if (!existing)
    return `${block}\n\n## Notes\n\nProject-specific notes for agents go here; \`shard docs\` keeps them.\n`
  const start = existing.indexOf(GENERATED_START)
  const end = existing.indexOf(GENERATED_END)
  if (start === -1 || end === -1) return `${block}\n\n${existing}`
  return `${existing.slice(0, start)}${block}${existing.slice(end + GENERATED_END.length)}`
}

/** Every generated file except AGENTS.md (see `mergeAgentsMd`), by project-relative path. */
export function generateDocs(
  manifest: ManifestValue,
  errors: readonly ErrorCode[],
): Record<string, string> {
  const files: Record<string, string> = {
    '.agents/components.md': renderComponentCatalog(),
    '.agents/errors.md': renderErrorCatalog(errors),
    '.agents/assets.md': renderAssetCatalog(),
    '.shard/schemas/shard.schema.json': `${JSON.stringify(manifestJsonSchema(), null, 2)}\n`,
    '.shard/schemas/scene.schema.json': `${JSON.stringify(sceneJsonSchema(), null, 2)}\n`,
  }
  for (const [name, content] of Object.entries(SKILLS))
    files[`.agents/skills/${name}`] = content.replaceAll('<project>', manifest.name)
  for (const def of allComponents()) {
    if (def.name.startsWith('test/')) continue
    files[`.shard/schemas/components/${def.name.replace('/', '.')}.json`] =
      `${JSON.stringify(def.jsonSchema(), null, 2)}\n`
  }
  return files
}
